fn flat(b: u8) -> char {
    FLAT.iter()
        .chain(FLAT_Y.iter())
        .find(|(x, _)| *x == b)
        .map_or(char::from(b), |(_, c)| *c)
}

fn pair(base: u8, tone: u8) -> Option<char> {
    PAIRS
        .iter()
        .find(|(b, t, _)| *b == base && *t == tone)
        .and_then(|(_, _, cp)| char::from_u32(*cp))
}

/// Decodes raw TCVN3 bytes: uppercase base+tone byte pairs fold to one precomposed
/// char, every other byte maps through the flat table (ASCII and unmapped bytes as
/// Latin-1).
pub fn decode(raw: &[u8]) -> String {
    let mut out = String::with_capacity(raw.len());
    let mut i = 0;
    while i < raw.len() {
        if let Some(&n) = raw.get(i + 1)
            && let Some(c) = pair(raw[i], n)
        {
            out.push(c);
            i += 2;
            continue;
        }
        out.push(flat(raw[i]));
        i += 1;
    }
    out
}
