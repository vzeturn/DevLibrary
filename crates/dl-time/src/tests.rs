#[test]
fn pattern_errors() {
    let dt = DateTime::parse_iso("2026-11-15T10:20:30").unwrap();
    assert_eq!(
        dt.format("dd/MM/yyyy ngày"),
        inv(11, "unknown pattern letter (quote literal text)")
    );
    assert_eq!(
        dt.format("yyyyyy"),
        inv(0, "too many repeated pattern letters")
    );
    assert_eq!(
        dt.format("ddddd"),
        inv(0, "too many repeated pattern letters")
    );
    assert_eq!(
        dt.format("HHH"),
        inv(0, "too many repeated pattern letters")
    );
    assert_eq!(
        dt.format("ffffffffff"),
        inv(0, "too many repeated pattern letters")
    );
    assert_eq!(dt.format("'abc"), inv(0, "unterminated quoted literal"));
    assert_eq!(dt.format("HH\\"), inv(2, "backslash at end of pattern"));
    assert_eq!(
        dt.format("HH zzz"),
        inv(3, "offset field in a pattern for a value without an offset")
    );
    assert_eq!(
        dt.format("K"),
        inv(0, "offset field in a pattern for a value without an offset")
    );
    assert_eq!(
        dt.date().format("dd HH"),
        inv(3, "time field in a pattern for a value without a time")
    );
    assert_eq!(
        dt.time().format("HH dd"),
        inv(3, "date field in a pattern for a value without a date")
    );
    assert_eq!(
        dt.format("g"),
        inv(0, "unknown pattern letter (quote literal text)")
    );
    assert!(Date::parse("15", "dd").is_err());
    assert_eq!(Date::parse("15", "dd"), inv(2, "pattern has no year (y)"));
    assert_eq!(
        OffsetDateTime::parse("2026", "yyyy"),
        inv(4, "pattern has no offset (zzz, zz, z or K)")
    );
    assert_eq!(
        Time::parse("10 15", "HH dd"),
        inv(3, "date field in a pattern for a value without a date")
    );
}

#[test]
fn custom_parse_round_trips() {
    let patterns = [
        "dd/MM/yyyy HH:mm:ss",
        "d/M/yyyy H:m:s",
        "dddd, MMMM d, yyyy h:mm:ss tt",
        "ddd, dd MMM yyyy HH:mm:ss.fffffffff",
        "yyyyMMddHHmmss.FFFFFFFFF",
        "yyyy-MM-dd'T'HH:mm:ss.FFF",
        "'Ngày' dd 'tháng' MM 'năm' yyyy, HH 'giờ'",
    ];
    let values = [
        "2026-11-15T10:20:30",
        "2026-01-05T00:07:09.123456789",
        "1999-12-31T23:59:59.5",
        "2024-02-29T12:00:00",
        "0001-01-01T00:00:00",
    ];
    for locale in [Locale::En, Locale::Vi] {
        for p in patterns {
            for v in values {
                let mut dt = DateTime::parse_iso(v).unwrap();
                if p.contains("HH 'giờ'") {
                    dt = DateTime::new(dt.date(), Time::from_hms(dt.hour(), 0, 0).unwrap());
                }
                if !p.contains('f') && !p.contains('F') {
                    dt = dt.with_nanosecond(0).unwrap();
                }
                if p.ends_with(".FFF") {
                    let ms = dt.nanosecond() / 1_000_000 * 1_000_000;
                    dt = dt.with_nanosecond(ms).unwrap();
                }
                let s = dt.format_locale(p, locale).unwrap();
                assert_eq!(DateTime::parse_locale(&s, p, locale), Ok(dt), "{p} {s}");
            }
        }
    }
}

