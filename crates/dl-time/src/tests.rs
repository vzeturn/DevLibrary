#[test]
fn rfc3339_invalid() {
    let parse = |offset, expected| Err(Error::Parse { offset, expected });
    let cases: [(&str, Result<OffsetDateTime, Error>); 24] = [
        ("2026-11-15T10:20:60Z", Err(Error::component("second", 60))),
        ("1990-12-31T23:59:60Z", Err(Error::component("second", 60))),
        ("2026-11-15T10:20Z", parse(16, "':' after minute")),
        ("2026-11-15T10:20:30", parse(19, "'Z' or a numeric offset")),
        ("2026-11-15T10:20:30.Z", parse(20, "fraction digits")),
        (
            "2026-11-15T10:20:30.1234567890Z",
            parse(29, "at most 9 fraction digits"),
        ),
        ("2026-11-15T10:20:30+07", parse(22, "':' in offset")),
        ("2026-11-15T10:20:30+0700", parse(22, "':' in offset")),
        (
            "2026-11-15T10:20:30+18:01",
            Err(Error::component("offset", 64_860)),
        ),
        (
            "2026-11-15T10:20:30+07:60",
            Err(Error::component("offset minute", 60)),
        ),
        (
            "2026-11-15T10:20:30+7:00",
            parse(20, "two-digit offset hour"),
        ),
        ("2026-13-15T10:20:30Z", Err(Error::component("month", 13))),
        ("2026-00-15T10:20:30Z", Err(Error::component("month", 0))),
        ("2026-02-29T10:20:30Z", Err(Error::component("day", 29))),
        ("2026-11-15T24:00:00Z", Err(Error::component("hour", 24))),
        ("2026-11-15T10:60:00Z", Err(Error::component("minute", 60))),
        (
            "2026-11-15X10:20:30Z",
            parse(10, "'T' between date and time"),
        ),
        ("26-11-15T10:20:30Z", parse(0, "four-digit year")),
        ("+2026-11-15T10:20:30Z", parse(0, "four-digit year")),
        ("2026-11-15T10:20:30Z ", parse(20, "end of input")),
        ("2026-11-15T1:20:30Z", parse(11, "two-digit hour")),
        (
            "2026-11-15T10:20:30,5Z",
            parse(19, "'Z' or a numeric offset"),
        ),
        ("2026/11/15T10:20:30Z", parse(4, "'-' after year")),
        ("", parse(0, "four-digit year")),
    ];
    for (input, expected) in cases {
        assert_eq!(OffsetDateTime::parse_rfc3339(input), expected, "{input}");
    }
    assert!(" 2026-11-15T10:20:30Z".parse::<OffsetDateTime>().is_err());
    assert!("2026-11-15T10:20:30ZZ".parse::<OffsetDateTime>().is_err());
    assert!("2026-11-15".parse::<OffsetDateTime>().is_err());
    assert!(
        "２０２６-11-15T10:20:30Z"
            .parse::<OffsetDateTime>()
            .is_err()
    );
}

