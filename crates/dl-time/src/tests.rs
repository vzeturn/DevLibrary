//! Cross-module tests: exhaustive calendar round trips, Python reference vectors,
//! RFC 3339 tables and custom patterns.

use crate::date::{MAX_DAYS, MIN_DAYS};
use crate::*;
use std::string::{String, ToString};
use std::vec::Vec;

fn date(y: i32, m: u8, d: u8) -> Date {
    Date::new(y, m, d).unwrap()
}

fn odt(s: &str) -> OffsetDateTime {
    OffsetDateTime::parse_rfc3339(s).unwrap()
}

fn inv<T>(offset: usize, reason: &'static str) -> Result<T, Error> {
    Err(Error::InvalidPattern { offset, reason })
}

fn perr<T>(offset: usize, expected: &'static str) -> Result<T, Error> {
    Err(Error::Parse { offset, expected })
}

#[test]
fn every_day_round_trips() {
    // -9999-01-01 ..= 9999-12-31: 7 304 484 days.
    let mut prev = Date::MIN;
    assert_eq!(prev.to_unix_days() as i64, MIN_DAYS);
    let mut weekday = prev.weekday();
    let mut ordinal = 1;
    for days in MIN_DAYS + 1..=MAX_DAYS {
        let d = Date::from_unix_days(days).unwrap();
        assert_eq!(d.to_unix_days() as i64, days);
        assert!(d > prev);
        assert_eq!(prev.succ(), d);
        weekday = weekday.succ();
        assert_eq!(d.weekday(), weekday);
        ordinal = if d.year() != prev.year() {
            1
        } else {
            ordinal + 1
        };
        assert_eq!(d.ordinal(), ordinal);
        assert_eq!(Date::new(d.year(), d.month().number(), d.day()), Ok(d));
        prev = d;
    }
    assert_eq!(prev, Date::MAX);
    assert_eq!(MAX_DAYS - MIN_DAYS + 1, 7_304_484);
}

#[test]
fn python_date_vectors() {
    // testdata/dates.txt is generated by testdata/gen_vectors.py from Python's datetime.
    let mut n = 0;
    for line in include_str!("../testdata/dates.txt")
        .lines()
        .filter(|l| !l.starts_with('#'))
    {
        let f: Vec<i64> = line.split(' ').map(|x| x.parse().unwrap()).collect();
        let d = date(f[0] as i32, f[1] as u8, f[2] as u8);
        assert_eq!(d.to_unix_days() as i64, f[3], "{line}");
        assert_eq!(Date::from_unix_days(f[3]), Ok(d));
        assert_eq!(d.weekday().days_from_monday() as i64, f[4], "{line}");
        assert_eq!(d.iso_week(), (f[5] as i32, f[6] as u8), "{line}");
        assert_eq!(d.weekday().iso_number() as i64, f[7], "{line}");
        assert_eq!(d.ordinal() as i64, f[8], "{line}");
        assert_eq!(Date::from_ordinal(d.year(), d.ordinal()), Ok(d));
        let wd = Weekday::from_iso_number(f[7] as u8).unwrap();
        assert_eq!(
            Date::from_iso_week(f[5] as i32, f[6] as u8, wd),
            Ok(d),
            "{line}"
        );
        assert_eq!(d.to_string().parse::<Date>(), Ok(d));
        n += 1;
    }
    assert_eq!(n, 500);
}

#[test]
fn python_unix_vectors() {
    let mut n = 0;
    for line in include_str!("../testdata/unix.txt")
        .lines()
        .filter(|l| !l.starts_with('#'))
    {
        let mut parts = line.splitn(3, ' ');
        let secs: i64 = parts.next().unwrap().parse().unwrap();
        let rfc = parts.next().unwrap();
        let http = parts.next().unwrap();
        let t = OffsetDateTime::from_unix_seconds(secs).unwrap();
        assert_eq!(t.to_rfc3339(), rfc);
        assert_eq!(t.to_http_date(), http);
        assert_eq!(odt(rfc).unix_seconds(), secs);
        assert_eq!(OffsetDateTime::parse_http_date(http), Ok(t));
        assert_eq!(t.unix_millis(), secs * 1000);
        assert_eq!(OffsetDateTime::from_unix_millis(secs * 1000), Ok(t));
        assert_eq!(t.unix_nanos(), secs as i128 * 1_000_000_000);
        // Same instant at +07:00 when representable.
        if let Some(vn) = t.checked_to_offset(Offset::VIETNAM) {
            assert_eq!(vn, t);
            assert_eq!(vn.unix_seconds(), secs);
            assert_eq!(vn.datetime() - t.datetime(), Duration::from_hours(7));
        }
        n += 1;
    }
    assert_eq!(n, 400);
}

#[test]
fn unix_conversions_and_overflow() {
    let t = OffsetDateTime::from_unix_millis(-1).unwrap();
    assert_eq!(t.to_rfc3339(), "1969-12-31T23:59:59.999Z");
    assert_eq!(
        (t.unix_seconds(), t.unix_millis(), t.unix_nanos()),
        (-1, -1, -1_000_000)
    );
    let t = OffsetDateTime::from_unix_nanos(-1).unwrap();
    assert_eq!(t.to_rfc3339(), "1969-12-31T23:59:59.999999999Z");
    assert_eq!((t.unix_seconds(), t.unix_millis()), (-1, -1));
    let t = OffsetDateTime::from_unix_nanos(1_500_000_000).unwrap();
    assert_eq!((t.unix_seconds(), t.unix_millis()), (1, 1500));
    // Python: datetime(1, 1, 1, tzinfo=timezone.utc).timestamp() == -62135596800
    // -9999-01-01 is 10 000 years (25 cycles of 146 097 days) before 0001-01-01.
    let min = -62_135_596_800 - 25 * 146_097 * 86_400;
    assert_eq!(
        OffsetDateTime::from_unix_seconds(min).unwrap().to_rfc3339(),
        "-9999-01-01T00:00:00Z"
    );
    assert_eq!(
        OffsetDateTime::from_unix_seconds(min - 1),
        Err(Error::Overflow)
    );
    assert_eq!(
        OffsetDateTime::from_unix_seconds(253_402_300_799)
            .unwrap()
            .to_rfc3339(),
        "9999-12-31T23:59:59Z"
    );
    assert_eq!(
        OffsetDateTime::from_unix_seconds(253_402_300_800),
        Err(Error::Overflow)
    );
    assert_eq!(
        OffsetDateTime::from_unix_seconds(i64::MAX),
        Err(Error::Overflow)
    );
    assert_eq!(
        OffsetDateTime::from_unix_seconds(i64::MIN),
        Err(Error::Overflow)
    );
    assert_eq!(
        OffsetDateTime::from_unix_millis(i64::MAX),
        Err(Error::Overflow)
    );
    assert_eq!(
        OffsetDateTime::from_unix_millis(i64::MIN),
        Err(Error::Overflow)
    );
    assert_eq!(
        OffsetDateTime::from_unix_nanos(i128::MAX),
        Err(Error::Overflow)
    );
    assert_eq!(
        OffsetDateTime::from_unix_nanos(i128::MIN),
        Err(Error::Overflow)
    );
    // JavaScript Date.now() style millisecond input.
    let js = OffsetDateTime::from_unix_millis(1_794_712_830_120).unwrap();
    assert_eq!(
        js.to_offset(Offset::VIETNAM).to_rfc3339(),
        "2026-11-15T10:20:30.120+07:00"
    );
}

